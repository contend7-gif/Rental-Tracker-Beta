function normalizeVersion(version: unknown) {
  return String(version || "")
    .trim()
    .replace(/^v/i, "");
}

export function compareReleaseVersions(left: unknown, right: unknown) {
  const leftParts = normalizeVersion(left).split(".").map((part) => Number.parseInt(part, 10) || 0);
  const rightParts = normalizeVersion(right).split(".").map((part) => Number.parseInt(part, 10) || 0);
  const maxLength = Math.max(leftParts.length, rightParts.length);

  for (let index = 0; index < maxLength; index += 1) {
    const delta = (leftParts[index] || 0) - (rightParts[index] || 0);
    if (delta !== 0) return delta;
  }

  return 0;
}

export function findReleaseNotesEntry(version: unknown) {
  const normalized = normalizeVersion(version);
  if (!normalized) return null;
  return RELEASE_NOTES.find((entry) => normalizeVersion(entry.version) === normalized) || null;
}

export function getRecentReleaseNotes(limit = 5) {
  return [...RELEASE_NOTES]
    .sort((left, right) => compareReleaseVersions(right.version, left.version))
    .slice(0, limit);
}
